#!/usr/bin/env python3
"""
Embeds frontend/dist/ into backend/src/assets.cpp as byte arrays, so
ProsperoMgr ships as one ELF with no separate files to deploy.

Usage: python3 tools/gen_assets.py (after `npm run build` in frontend/).
"""

import gzip
import mimetypes
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST_DIR = ROOT / "frontend" / "dist"
OUT_FILE = ROOT / "backend" / "src" / "assets.cpp"

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
}

# Text formats compress well and are the bulk of the bundle's weight; png/woff2/ico
# are already compressed, so gzipping them again just burns CPU for no size win.
COMPRESSIBLE_EXTENSIONS = {".html", ".js", ".css", ".json", ".svg"}


def content_type_for(path: Path) -> str:
    if path.suffix in CONTENT_TYPES:
        return CONTENT_TYPES[path.suffix]
    guessed, _ = mimetypes.guess_type(path.name)
    return guessed or "application/octet-stream"


def c_identifier(url_path: str) -> str:
    return "kAsset_" + "".join(c if c.isalnum() else "_" for c in url_path)


def emit_byte_array(out, name: str, data: bytes) -> None:
    out.write(f"const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 20):
        chunk = data[i : i + 20]
        out.write("  " + ",".join(str(b) for b in chunk) + ",\n")
    out.write("};\n")


def main() -> int:
    if not DIST_DIR.is_dir():
        print(f"error: {DIST_DIR} not found — run `npm run build` in frontend/ first", file=sys.stderr)
        return 1

    files = sorted(p for p in DIST_DIR.rglob("*") if p.is_file())
    if not files:
        print(f"error: {DIST_DIR} is empty", file=sys.stderr)
        return 1

    entries = []  # (url_path, c_name, content_type, size, gzip)
    raw_total = 0

    with OUT_FILE.open("w") as out:
        out.write(
            "// GENERATED by tools/gen_assets.py from frontend/dist/ — do not hand-edit.\n"
            "// Re-run `npm run build` (frontend/) then `python3 tools/gen_assets.py` to refresh.\n\n"
            '#include "assets.hpp"\n\n'
            "#include <cstring>\n\n"
            "namespace prospero {\n\n"
            "namespace {\n\n"
        )

        for path in files:
            rel = path.relative_to(DIST_DIR).as_posix()
            url_path = "/" + rel
            data = path.read_bytes()
            raw_total += len(data)
            use_gzip = path.suffix in COMPRESSIBLE_EXTENSIONS
            # mtime=0 keeps the compressed bytes identical across builds of the
            # same input — otherwise gzip stamps the header with the build time.
            encoded = gzip.compress(data, compresslevel=9, mtime=0) if use_gzip else data
            name = c_identifier(url_path)
            emit_byte_array(out, name, encoded)
            entries.append((url_path, name, content_type_for(path), len(encoded), use_gzip))

        out.write(
            "\nstruct Asset {\n"
            "    const char *path;\n"
            "    const unsigned char *data;\n"
            "    unsigned int size;\n"
            "    const char *content_type;\n"
            "    bool gzip;\n"
            "};\n\n"
            "const Asset kAssets[] = {\n"
        )
        for url_path, name, ctype, size, use_gzip in entries:
            out.write(f'    {{"{url_path}", {name}, {size}, "{ctype}", {"true" if use_gzip else "false"}}},\n')
        out.write(
            "};\n"
            "constexpr size_t kAssetsCount = sizeof(kAssets) / sizeof(kAssets[0]);\n\n"
            "const Asset *FindAsset(const std::string &path) {\n"
            "    for (size_t i = 0; i < kAssetsCount; i++) {\n"
            "        if (path == kAssets[i].path) return &kAssets[i];\n"
            "    }\n"
            "    return nullptr;\n"
            "}\n\n"
            "// Pre-gzipped at build time — every browser this server ever talks to sends\n"
            "// Accept-Encoding: gzip, so there's no plain fallback to negotiate.\n"
            "HttpResponse MakeAssetResponse(const Asset *a) {\n"
            "    HttpResponse resp{200, a->content_type,\n"
            "                      std::string(reinterpret_cast<const char *>(a->data), a->size)};\n"
            '    if (a->gzip) resp.extra_headers["Content-Encoding"] = "gzip";\n'
            "    // Hashed /assets files never change, so the console's browser can skip re-fetching them.\n"
            '    bool hashed = std::strncmp(a->path, "/assets/", 8) == 0;\n'
            '    resp.extra_headers["Cache-Control"] = hashed ? "public, max-age=31536000, immutable" : "no-cache";\n'
            "    return resp;\n"
            "}\n\n"
            "} // namespace\n\n"
            "HttpResponse ServeEmbeddedAsset(const std::string &url) {\n"
            '    std::string path = (url == "/") ? "/index.html" : url;\n\n'
            "    if (const Asset *a = FindAsset(path)) return MakeAssetResponse(a);\n\n"
            "    // SPA fallback: a path with no file extension in its last segment is\n"
            "    // assumed to be a client-side route, so serve index.html for it.\n"
            "    size_t last_slash = path.find_last_of('/');\n"
            "    std::string last_seg = path.substr(last_slash + 1);\n"
            '    if (last_seg.find(\'.\') == std::string::npos) {\n'
            '        if (const Asset *index = FindAsset("/index.html")) return MakeAssetResponse(index);\n'
            "    }\n\n"
            '    return HttpResponse::Error("asset not found", 404);\n'
            "}\n\n"
            "} // namespace prospero\n"
        )

    total_bytes = sum(size for _, _, _, size, _ in entries)
    saved_pct = (1 - total_bytes / raw_total) * 100 if raw_total else 0
    print(f"wrote {OUT_FILE.relative_to(ROOT)}: {len(entries)} assets, "
          f"{total_bytes} bytes ({raw_total} uncompressed, {saved_pct:.0f}% smaller)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
